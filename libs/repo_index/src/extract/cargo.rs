//! Crate cards from `Cargo.toml` (`makepad_toml_parser`): name, description, path dependencies
//! per target, dependents, and the `libs/app_registry/apps.json` apps that reach the crate.
//!
//! Dependencies are `dependencies` and `build-dependencies`, plain and under each
//! `target.<cfg>`, never `dev-dependencies`; only path dependencies count (directly, or through
//! `workspace = true` and the nearest workspace's `workspace.dependencies`). A path that leaves
//! the tracked tree (a private `apps/commercial` clone, an ignored directory) marks the card's
//! `private_members`. Dependents are package directories.

use crate::CrateCard;
use makepad_toml_parser::{parse_toml, Toml, TomlTable};
use std::collections::{BTreeMap, HashMap, HashSet, VecDeque};

/// Where the app registry lives in a tree.
pub const APPS_JSON: &str = "libs/app_registry/apps.json";
/// The first line of a crates.io port's manifest (a vendored crate).
const CARGO_NORMALIZED: &str = "THIS FILE IS AUTOMATICALLY GENERATED BY CARGO";

#[derive(Clone, Debug, Default)]
pub struct Package {
    pub name: String,
    /// The package directory, `""` for the tree root.
    pub dir: String,
    pub description: String,
    /// A crates.io port (its manifest is cargo-normalized): its files are skeletons.
    pub vendored: bool,
    /// The crate root files, for the card's module list.
    pub roots: Vec<String>,
    pub targets: Vec<String>,
    /// Resolved path dependencies: `(package index, cfg)`.
    pub deps: Vec<(usize, String)>,
    pub dependents: Vec<usize>,
    pub apps: Vec<String>,
    pub rs_files: u32,
    pub private_members: bool,
}

#[derive(Debug, Default)]
pub struct Graph {
    pub packages: Vec<Package>,
    by_dir: BTreeMap<String, usize>,
    /// Manifests that failed to parse, with why.
    pub errors: Vec<(String, String)>,
}

/// A dependency as written: a normalized path, or a workspace key, under a cfg.
enum RawDep {
    Path { path: String, cfg: String, name: String },
    Workspace { key: String, cfg: String, name: String },
}

fn dir_of(path: &str) -> &str {
    path.rfind('/').map_or("", |i| &path[..i])
}

/// `dir` joined with a relative `rel`, `..` resolved; `None` when it leaves the tree.
pub fn join(dir: &str, rel: &str) -> Option<String> {
    let mut parts: Vec<&str> = dir.split('/').filter(|p| !p.is_empty()).collect();
    for seg in rel.split('/') {
        match seg {
            "" | "." => {}
            ".." => {
                parts.pop()?;
            }
            s => parts.push(s),
        }
    }
    Some(parts.join("/"))
}

fn str_of(t: &Toml) -> Option<&str> {
    t.as_str()
}

fn deps_in(table: &TomlTable, cfg: &str, out: &mut Vec<RawDep>, dir: &str, escapes: &mut bool) {
    for section in ["dependencies", "build-dependencies"] {
        let Some(Toml::Table(deps)) = table.get(section) else { continue };
        for (key, spec) in deps {
            let Toml::Table(spec) = spec else { continue };
            // the package name as written: `package = ".."` renames the key
            let name = spec.get("package").and_then(str_of).unwrap_or(key).to_string();
            if let Some(path) = spec.get("path").and_then(str_of) {
                match join(dir, path) {
                    Some(p) => out.push(RawDep::Path { path: p, cfg: cfg.to_string(), name }),
                    None => *escapes = true,
                }
            } else if spec.get("workspace").and_then(|w| w.as_bool()) == Some(true) {
                out.push(RawDep::Workspace { key: key.clone(), cfg: cfg.to_string(), name });
            }
        }
    }
}

struct Parsed {
    package: Option<(Package, Vec<RawDep>)>,
    /// `workspace.dependencies` keys with a path, normalized.
    workspace: Option<HashMap<String, String>>,
}

fn parse(path: &str, text: &str, files: &HashSet<&str>) -> Result<Parsed, String> {
    let doc = parse_toml(text).map_err(|e| format!("{} (byte {})", e.msg, e.span.start))?;
    let dir = dir_of(path).to_string();
    let workspace = match doc.get_path(&["workspace"]) {
        Some(Toml::Table(ws)) => {
            let mut keys = HashMap::new();
            if let Some(Toml::Table(deps)) = ws.get("dependencies") {
                for (key, spec) in deps {
                    if let Some(p) = spec.as_table().and_then(|t| t.get("path")).and_then(str_of) {
                        if let Some(full) = join(&dir, p) {
                            keys.insert(key.clone(), full);
                        }
                    }
                }
            }
            Some(keys)
        }
        _ => None,
    };
    let Some(Toml::Table(pkg)) = doc.get_path(&["package"]) else {
        return Ok(Parsed { package: None, workspace });
    };
    let name = pkg.get("name").and_then(str_of).unwrap_or_default().to_string();
    let description = pkg.get("description").and_then(str_of).unwrap_or_default().trim().to_string();
    let file = |rel: &str| join(&dir, rel).filter(|p| files.contains(p.as_str()));
    let mut targets = Vec::new();
    let mut roots = Vec::new();
    let lib_path = match doc.get_path(&["lib"]) {
        Some(Toml::Table(lib)) => Some(lib.get("path").and_then(str_of).unwrap_or("src/lib.rs").to_string()),
        _ => file("src/lib.rs").map(|_| "src/lib.rs".to_string()),
    };
    if let Some(lp) = lib_path {
        targets.push("lib".to_string());
        roots.extend(file(&lp));
    }
    let mut main_is_bin = false;
    if let Some(bins) = doc.get_path(&["bin"]).and_then(|b| b.as_array_of_tables()) {
        for b in bins {
            let bname = b.get("name").and_then(str_of).unwrap_or(&name);
            let bpath = b.get("path").and_then(str_of).unwrap_or("src/main.rs");
            main_is_bin |= bpath == "src/main.rs";
            targets.push(format!("bin {bname}"));
            if roots.is_empty() {
                roots.extend(file(bpath));
            }
        }
    }
    if !main_is_bin && file("src/main.rs").is_some() {
        targets.push(format!("bin {name}"));
        if roots.is_empty() {
            roots.extend(file("src/main.rs"));
        }
    }
    let mut raw = Vec::new();
    let mut escapes = false;
    deps_in(&doc.root, "", &mut raw, &dir, &mut escapes);
    if let Some(Toml::Table(targets_table)) = doc.get_path(&["target"]) {
        for (cfg, t) in targets_table {
            if let Toml::Table(t) = t {
                deps_in(t, cfg, &mut raw, &dir, &mut escapes);
            }
        }
    }
    let package = Package {
        name,
        dir,
        description,
        vendored: text.lines().take(3).any(|l| l.contains(CARGO_NORMALIZED)),
        roots,
        targets,
        private_members: escapes,
        ..Default::default()
    };
    Ok(Parsed { package: Some((package, raw)), workspace })
}

/// A card from one manifest alone (the overlay): its dependencies by the names written (path
/// and `workspace = true` ones, unresolved), and no dependents, apps, file counts or modules.
pub fn written_card(path: &str, text: &str) -> Result<Option<(String, CrateCard, bool)>, String> {
    let parsed = parse(path, text, &HashSet::new())?;
    let Some((p, raw)) = parsed.package else { return Ok(None) };
    let deps = raw
        .into_iter()
        .map(|d| match d {
            RawDep::Path { cfg, name, .. } | RawDep::Workspace { cfg, name, .. } => (name, cfg),
        })
        .collect();
    let card = CrateCard {
        dir: p.dir.clone(),
        description: p.description.clone(),
        deps,
        targets: p.targets.clone(),
        private_members: p.private_members,
        ..Default::default()
    };
    Ok(Some((p.name, card, p.vendored)))
}

impl Graph {
    /// The graph of a tree: `manifests` are `(path, text)` of every `Cargo.toml`, `files` every
    /// tracked path, `apps_json` the registry's text when present.
    pub fn build(manifests: &[(String, String)], files: &[&str], apps_json: Option<&str>) -> Graph {
        let file_set: HashSet<&str> = files.iter().copied().collect();
        let mut g = Graph::default();
        let mut raws: Vec<Vec<RawDep>> = Vec::new();
        let mut workspaces: BTreeMap<String, HashMap<String, String>> = BTreeMap::new();
        for (path, text) in manifests {
            match parse(path, text, &file_set) {
                Ok(parsed) => {
                    if let Some(ws) = parsed.workspace {
                        workspaces.insert(dir_of(path).to_string(), ws);
                    }
                    if let Some((p, raw)) = parsed.package {
                        g.by_dir.insert(p.dir.clone(), g.packages.len());
                        g.packages.push(p);
                        raws.push(raw);
                    }
                }
                Err(e) => g.errors.push((path.clone(), e)),
            }
        }
        for (i, raw) in raws.into_iter().enumerate() {
            let dir = g.packages[i].dir.clone();
            for dep in raw {
                let (path, cfg) = match dep {
                    RawDep::Path { path, cfg, .. } => (Some(path), cfg),
                    RawDep::Workspace { key, cfg, .. } => {
                        // the nearest enclosing workspace that declares the key
                        let found = workspaces
                            .iter()
                            .filter(|(wdir, _)| wdir.is_empty() || dir == **wdir || dir.starts_with(&format!("{wdir}/")))
                            .max_by_key(|(wdir, _)| wdir.len())
                            .and_then(|(_, keys)| keys.get(&key).cloned());
                        match found {
                            Some(p) => (Some(p), cfg),
                            // a registry dependency through the workspace: not a path dependency
                            None => (None, cfg),
                        }
                    }
                };
                let Some(path) = path else { continue };
                match g.by_dir.get(&path) {
                    Some(&j) => {
                        if !g.packages[i].deps.iter().any(|(d, c)| *d == j && *c == cfg) {
                            g.packages[i].deps.push((j, cfg));
                        }
                    }
                    None => g.packages[i].private_members = true,
                }
            }
        }
        for i in 0..g.packages.len() {
            let deps: Vec<usize> = g.packages[i].deps.iter().map(|(d, _)| *d).collect();
            for d in deps {
                if !g.packages[d].dependents.contains(&i) {
                    g.packages[d].dependents.push(i);
                }
            }
        }
        for f in files.iter().filter(|f| f.ends_with(".rs")) {
            if let Some(i) = g.package_of(f) {
                g.packages[i].rs_files += 1;
            }
        }
        if let Some(text) = apps_json {
            match makepad_strict_json::parse(text.as_bytes()) {
                Ok(makepad_strict_json::Value::Arr(apps)) => {
                    for app in apps {
                        let (Some(id), Some(pkg)) = (app.get("id").and_then(|v| v.as_str()), app.get("package").and_then(|v| v.as_str())) else {
                            continue;
                        };
                        for i in g.closure(pkg) {
                            g.packages[i].apps.push(id.to_string());
                        }
                    }
                }
                Ok(_) => g.errors.push((APPS_JSON.into(), "not a JSON array".into())),
                Err(e) => g.errors.push((APPS_JSON.into(), e.to_string())),
            }
        }
        g
    }

    /// Packages a package reaches through path dependencies, itself included.
    fn closure(&self, name: &str) -> Vec<usize> {
        let mut seen = HashSet::new();
        let mut queue: VecDeque<usize> = self.packages.iter().enumerate().filter(|(_, p)| p.name == name).map(|(i, _)| i).collect();
        while let Some(i) = queue.pop_front() {
            if seen.insert(i) {
                queue.extend(self.packages[i].deps.iter().map(|(d, _)| *d));
            }
        }
        let mut out: Vec<usize> = seen.into_iter().collect();
        out.sort();
        out
    }

    /// The package whose directory is the longest prefix of `path`.
    pub fn package_of(&self, path: &str) -> Option<usize> {
        let mut dir = dir_of(path);
        loop {
            if let Some(&i) = self.by_dir.get(dir) {
                return Some(i);
            }
            if dir.is_empty() {
                return None;
            }
            dir = dir_of(dir);
        }
    }

    pub fn card(&self, i: usize, modules: Vec<String>) -> CrateCard {
        let p = &self.packages[i];
        CrateCard {
            dir: p.dir.clone(),
            description: p.description.clone(),
            deps: p.deps.iter().map(|(d, cfg)| (self.packages[*d].name.clone(), cfg.clone())).collect(),
            dependents: p.dependents.iter().map(|d| self.packages[*d].dir.clone()).collect(),
            apps: p.apps.clone(),
            targets: p.targets.clone(),
            rs_files: p.rs_files,
            modules,
            private_members: p.private_members,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn fixture() -> (Vec<(String, String)>, Vec<&'static str>) {
        let manifests = vec![
            ("Cargo.toml".to_string(), include_str!("../../fixture/Cargo.toml").to_string()),
            ("alpha/Cargo.toml".to_string(), include_str!("../../fixture/alpha/Cargo.toml").to_string()),
            ("beta/Cargo.toml".to_string(), include_str!("../../fixture/beta/Cargo.toml").to_string()),
        ];
        let files = vec!["Cargo.toml", "alpha/Cargo.toml", "alpha/src/lib.rs", "alpha/src/tables.rs", "beta/Cargo.toml", "beta/src/lib.rs", "beta/src/broken.rs", "libs/app_registry/apps.json"];
        (manifests, files)
    }

    #[test]
    fn fixture_graph() {
        let (manifests, files) = fixture();
        let g = Graph::build(&manifests, &files, Some(include_str!("../../fixture/libs/app_registry/apps.json")));
        assert!(g.errors.is_empty(), "{:?}", g.errors);
        let alpha = g.package_of("alpha/src/lib.rs").unwrap();
        let beta = g.package_of("beta/src/broken.rs").unwrap();
        let a = g.card(alpha, vec!["tables".into()]);
        assert_eq!(a.description, "Spinning gizmos for the index fixture");
        assert_eq!(a.deps, vec![("fixture-beta".to_string(), String::new())]);
        assert_eq!(a.targets, vec!["lib".to_string()]);
        assert_eq!(a.rs_files, 2);
        assert_eq!(a.apps, vec!["spinner".to_string()]);
        let b = g.card(beta, vec![]);
        assert_eq!(b.description, "");
        assert_eq!(b.dependents, vec!["alpha".to_string()]);
        assert_eq!(b.apps, vec!["spinner".to_string()], "apps reach transitively");
        assert!(g.package_of("README.md").is_none());
    }

    #[test]
    fn workspace_targets_private_and_ports() {
        let manifests = vec![
            ("Cargo.toml".to_string(), "[workspace]\nmembers=[]\n[workspace.dependencies]\nlexer = { path = \"libs/lexer\" }\nregistry = \"1\"\n".to_string()),
            ("libs/lexer/Cargo.toml".to_string(), "[package]\nname = \"lexer\"\n".to_string()),
            (
                "tools/run/Cargo.toml".to_string(),
                "[package]\nname = \"run\"\ndescription = \"\"\"\n  Runs\n\"\"\"\n[[bin]]\nname = \"makepad\"\npath = \"src/main.rs\"\n[dependencies]\nlexer = { workspace = true }\nregistry = { workspace = true }\nprivate = { path = \"../../apps/commercial/x\" }\nescape = { path = \"../../../outside\" }\n[target.'cfg(unix)'.dependencies]\nlexer2 = { path = \"../../libs/lexer\", package = \"lexer\" }\n[dev-dependencies]\ntestonly = { path = \"../../libs/lexer\" }\n".to_string(),
            ),
            ("libs/port/Cargo.toml".to_string(), format!("# {CARGO_NORMALIZED}\n[package]\nname = \"port\"\n")),
        ];
        let files = vec!["tools/run/src/main.rs", "libs/lexer/src/lib.rs"];
        let g = Graph::build(&manifests, &files, None);
        let run = g.package_of("tools/run/src/main.rs").unwrap();
        let card = g.card(run, vec![]);
        assert_eq!(card.description, "Runs");
        assert_eq!(card.targets, vec!["bin makepad".to_string()]);
        assert_eq!(card.deps, vec![("lexer".to_string(), String::new()), ("lexer".to_string(), "cfg(unix)".to_string())]);
        assert!(card.private_members);
        let lexer = g.package_of("libs/lexer/src/lib.rs").unwrap();
        assert_eq!(g.card(lexer, vec![]).dependents, vec!["tools/run".to_string()]);
        assert!(g.packages.iter().find(|p| p.name == "port").unwrap().vendored);
        assert!(!g.packages[run].vendored);
        let (name, card, vendored) = written_card("tools/run/Cargo.toml", &manifests[2].1).unwrap().unwrap();
        assert_eq!(name, "run");
        assert!(!vendored);
        assert_eq!(
            card.deps.iter().map(|(n, c)| format!("{n}{c}")).collect::<Vec<_>>(),
            vec!["lexer", "private", "registry", "lexercfg(unix)"]
        );
        assert!(card.private_members, "a path leaving the tree");
    }
}
